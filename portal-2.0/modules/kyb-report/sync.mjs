/* Sync Demo 3 report assets into this standalone module's vendor/.

   Run after demo-3 report CSS/JS change:
     node portal-2.0/modules/kyb-report/sync.mjs

   The module does not load demo-3 at runtime — only these vendored copies
   plus TDS tokens/Components. */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const DEMO3 = join(HERE, "..", "..", "demo-3");
const VENDOR = join(HERE, "vendor");
const REPO = join(HERE, "..", "..", "..");

mkdirSync(join(VENDOR, "css"), { recursive: true });
mkdirSync(join(VENDOR, "js"), { recursive: true });
mkdirSync(join(VENDOR, "ubo-graph-dist"), { recursive: true });

const COPIES = [
  ["css/d3-kyb-findings.css", "css/d3-kyb-findings.css"],
  ["css/d3-kyb-report-panels.css", "css/d3-kyb-report-panels.css"],
  ["css/d3-kyb-result-tabs.css", "css/d3-kyb-result-tabs.css"],
  ["css/d3-kyb-ubo-graph.css", "css/d3-kyb-ubo-graph.css"],
  ["js/d3-kyb-report-panels-data.js", "js/d3-kyb-report-panels-data.js"],
  ["js/d3-kyb-report-panels.js", "js/d3-kyb-report-panels.js"],
  ["js/d3-kyb-result-tabs.js", "js/d3-kyb-result-tabs.js"],
  ["js/d3-kyb-ubo-graph.js", "js/d3-kyb-ubo-graph.js"],
  [
    "transactions/kyb-results/ubo-graph-dist/ubo-graph.bundle.js",
    "ubo-graph-dist/ubo-graph.bundle.js"
  ],
  [
    "transactions/kyb-results/ubo-graph-dist/kyb-ubo-graph-react.css",
    "ubo-graph-dist/kyb-ubo-graph-react.css"
  ]
];

for (const [from, to] of COPIES) {
  copyFileSync(join(DEMO3, from), join(VENDOR, to));
  console.log("copied", to);
}

/* Extract Raw Data dialog styles from agent CSS; adapt for .kr-host. */
const agent = readFileSync(join(DEMO3, "css/d3-kyb-agent.css"), "utf8");
const rawStart = agent.indexOf("/* Raw Data — KYB Results json panel */");
const rawEnd = agent.indexOf("/* Business list rows:", rawStart);
if (rawStart >= 0 && rawEnd > rawStart) {
  let rawCss = agent.slice(rawStart, rawEnd).trim() + "\n";
  rawCss = rawCss.replaceAll(
    ".d3-workspace .d3-kyb-raw-dialog",
    ".kr-dialogs .d3-kyb-raw-dialog, .kr-host .d3-kyb-raw-dialog"
  );
  writeFileSync(join(VENDOR, "css/d3-kyb-raw-dialog.css"), rawCss);
  console.log("wrote css/d3-kyb-raw-dialog.css");
}

/* Extract score + raw dialog markup from demo-3/index.html → dialogs-markup.js */
const html = readFileSync(join(DEMO3, "index.html"), "utf8");

function dialogBlock(idAttr) {
  const idPos = html.indexOf(`id="${idAttr}"`);
  if (idPos < 0) throw new Error("dialog id not found: " + idAttr);
  const start = html.lastIndexOf("<div class=\"tds-dialog", idPos);
  let i = start;
  let depth = 0;
  while (i < html.length) {
    if (html.startsWith("<div", i)) {
      depth += 1;
      i = html.indexOf(">", i) + 1;
      continue;
    }
    if (html.startsWith("</div>", i)) {
      depth -= 1;
      i += 6;
      if (depth === 0) return html.slice(start, i);
      continue;
    }
    i += 1;
  }
  throw new Error("unclosed dialog: " + idAttr);
}

const markup = {
  raw: dialogBlock("d3-kyb-raw-dialog"),
  score: dialogBlock("kyb-score-breakdown-dialog")
};
writeFileSync(
  join(VENDOR, "js/dialogs-markup.js"),
  `/* Auto-extracted Demo 3 dialogs — regenerated by sync.mjs */\n` +
    `(function (global) {\n` +
    `  "use strict";\n` +
    `  global.KybReportDialogMarkup = ${JSON.stringify(markup)};\n` +
    `})(typeof window !== "undefined" ? window : globalThis);\n`
);
console.log("wrote js/dialogs-markup.js");

writeFileSync(
  join(VENDOR, "SYNCED"),
  `Synced from demo-3 at ${new Date().toISOString()}\n` +
    COPIES.map(([, to]) => to).join("\n") +
    "\ncss/d3-kyb-raw-dialog.css\njs/dialogs-markup.js\n"
);

console.log("Done. Workspace chrome stays in css/chrome.css (module-owned).");
/* silence unused */
void REPO;
