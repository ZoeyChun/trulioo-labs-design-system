/* ------------------------------------------------------------------
   index.html — the workspace canvas
   ------------------------------------------------------------------ */
function buildIndex(src) {
  let html = src;

  /* 1 · Header comment. The parent's opens the file and ends at the
     first "-->". */
  const headerEnd = html.indexOf("-->");
  if (headerEnd < 0 || headerEnd > 400) {
    throw new Error("build.mjs: could not find the parent's leading comment.");
  }
  html = FORK_HEADER + html.slice(headerEnd + 3);

  /* 2 · <base>, so every relative URL resolves against demo-3/. */
  html = sub(
    html,
    `<meta name="viewport" content="width=device-width, initial-scale=1.0">`,
    `<meta name="viewport" content="width=device-width, initial-scale=1.0">\n  <base href="../">`,
    "base href"
  );

  /* 3 · Title. */
  html = sub(
    html,
    `<title>Portal Demo 3 — Trulioo</title>`,
    `<title>Portal Demo 3 — KYB workspace</title>`,
    "title"
  );

  /* 4 · The fork's stylesheets, last in the cascade so they beat the
     hero-critical block the parent inlines just above </head>. */
  html = sub(
    html,
    `</head>`,
    `
  <!-- Last in the cascade so it beats the hero-critical block above. -->
  <link rel="stylesheet" href="kyb-workspace/css/workspace-canvas.css?v=16">
  <link rel="stylesheet" href="kyb-workspace/css/landing-layouts.css?v=21">
</head>`,
    "fork stylesheets"
  );

  /* 5 · Shell attributes.

     data-d3-lab is d3-nav.js's own escape hatch: without it the nav
     forces every page to the home view on load. With it the page owns
     its initial view, so this one opens straight into KYB — which is
     the only thing it is for. kyb-boot.js calls the resume surface
     once the agent scripts have bound.

     The rail is the parent's, in full. An earlier pass trimmed it to
     KYB + Settings; that is what made the sidebar look like a
     different build once the parent gained its Chats menu. */
  html = sub(
    html,
    `<div class="d1-shell" data-d3-view="home" data-d3-chat="closed" data-d3-home-skin="dark">`,
    `<div class="d1-shell kw-shell" data-d3-lab data-d3-view="chat" data-d3-chat="open"\n     data-d3-chat-mode="kyb" data-d3-home-skin="dark">`,
    "shell attributes"
  );

  /* 6 · The stage wraps <main>, it does not reach inside it — so every
     surface that already lives there (slot, drawer, map, report) keeps
     the layout it has in the parent. */
  html = sub(
    html,
    `  <main class="d1-main" data-d1-drawer="closed">`,
    `  <!-- Workspace canvas.
       .kw-stage wraps .d1-main rather than reaching inside it, so every
       existing surface (.d1-slot, .d1-drawer, the KYB views) keeps the
       layout it has in the parent page. The stage adds two things: the
       neutral-02 ground with the dot field painted on it, and the white
       sheet the content sits on. -->
  <div class="kw-stage" data-kw-stage>
    <canvas class="kw-stage__dots" id="kw-stage-dots" aria-hidden="true"></canvas>

${LANDING_LAB}

    <div class="kw-stage__body">
  <main class="d1-main" data-d1-drawer="closed">`,
    "stage open"
  );

  html = sub(
    html,
    `  </main>`,
    `  </main>
    </div><!-- /.kw-stage__body -->
  </div><!-- /.kw-stage -->`,
    "stage close"
  );

  /* 7 · Landing lab axes. The parent already carries
     data-d3-kyb-landing; these are the two the lab drives. */
  html = sub(
    html,
    `<div class="d3-workspace__landing" data-d3-kyb-landing>`,
    `<div class="d3-workspace__landing" data-d3-kyb-landing data-kw-group="open" data-kw-recent="list">`,
    "landing axes"
  );

  /* 8 · auth-gate → the shim. */
  const authGate = html.match(/<script src="js\/auth-gate\.js[^"]*"><\/script>/);
  if (!authGate) throw new Error("build.mjs: auth-gate script tag not found.");
  html = sub(html, authGate[0], AUTH_SHIM, "auth-gate shim");

  /* 9 · The fork's scripts, last so they observe the shell after every
     shared script has bound. */
  html = sub(
    html,
    `</body>`,
    `
<!-- Workspace canvas: dot ground, docked-panel guard.
     Last so it can observe the shell after every shared script has bound. -->
<script src="kyb-workspace/js/workspace-canvas.js?v=5"></script>
<script src="kyb-workspace/js/landing-layouts.js?v=12"></script>
<script src="kyb-workspace/js/kyb-boot.js?v=1"></script>
</body>`,
    "fork scripts"
  );

  return html;
}

/* ------------------------------------------------------------------
   report.html — the same page, booted onto one finished report
   ------------------------------------------------------------------ */
function buildReport(indexHtml) {
  let html = indexHtml;

  html = sub(
    html,
    `<!-- Demo 3 — KYB workspace canvas.`,
    `<!-- Demo 3 — KYB report, isolated.

     GENERATED — see kyb-workspace/build.mjs.

     Same shell and the same scripts as index.html; the only difference
     is that it boots straight into the finished report for one business
     (Apex Nordic Logistics AB) instead of the landing, and the report
     card is driven by js/report-views.js.

     Original header follows.

     Demo 3 — KYB workspace canvas.`,
    "report header"
  );

  html = sub(
    html,
    `<title>Portal Demo 3 — KYB workspace</title>`,
    `<title>Portal Demo 3 — KYB report</title>`,
    "report title"
  );

  html = sub(
    html,
    `  <link rel="stylesheet" href="kyb-workspace/css/landing-layouts.css?v=21">`,
    `  <link rel="stylesheet" href="kyb-workspace/css/landing-layouts.css?v=21">\n  <link rel="stylesheet" href="kyb-workspace/css/report-views.css?v=13">`,
    "report stylesheet"
  );

  /* The report lab replaces the landing's — only one surface shows at
     a time, and two lab panels stacked top-right is two too many. */
  html = sub(html, LANDING_LAB, REPORT_LAB, "report lab");

  /* The view axis lives on the report card itself. */
  html = sub(
    html,
    `<article class="d3-workspace__card d3-kyb-resume" data-d3-kyb-resume hidden>`,
    `<article class="d3-workspace__card d3-kyb-resume" data-d3-kyb-resume\n                 data-kw-view="feed" hidden>`,
    "report card view axis"
  );

  /* Name every generatable panel. A panel without data-kw-label is one
     the views never offer (raw, sources) — they feed the dialog and the
     signals panel rather than being sections of their own. */
  for (const [key, label] of Object.entries(PANEL_LABELS)) {
    const open = `<div class="d3-kyb-panel" data-d3-kyb-panel="${key}"`;
    html = sub(
      html,
      open,
      `<div class="d3-kyb-panel" data-d3-kyb-panel="${key}" data-kw-label="${label}"`,
      `panel label: ${key}`
    );
  }

  html = sub(
    html,
    `<script src="kyb-workspace/js/kyb-boot.js?v=1"></script>`,
    `<script src="kyb-workspace/js/kyb-boot.js?v=1"></script>\n<script src="kyb-workspace/js/report-boot.js?v=1"></script>\n<script src="kyb-workspace/js/report-views.js?v=9"></script>`,
    "report scripts"
  );

  return html;
}

/* ------------------------------------------------------------------ */
const parent = readFileSync(PARENT, "utf8");
const index = buildIndex(parent);
const report = buildReport(index);

writeFileSync(join(HERE, "index.html"), index);
writeFileSync(join(HERE, "report.html"), report);

console.log("kyb-workspace: rebuilt index.html and report.html from ../index.html");
