/* ============================================================
   Demo 3 — KYB workspace: regenerate the fork from the parent
   ============================================================
   Run after ../index.html moves:

     node portal-2.0/demo-3/kyb-workspace/build.mjs

   WHY THIS EXISTS. kyb-workspace/index.html and report.html are forks
   of ../index.html, and that page is under active development — it has
   gained a Chats rail, a verification wizard, chat history, the AI
   panel treatments and a Findings tab since this fork was cut. Hand-
   merging drifted twice, and the second time the fork was missing ten
   stylesheets and thirteen scripts: the sidebar and the chat
   suggestions were visibly a different build of the same product.

   So the fork is no longer a copy that is maintained. It is a
   PROJECTION of the parent plus the small, named set of deltas below,
   and this script applies them. Everything else — markup, assets,
   script order, cache-busting versions — comes from the parent by
   construction and cannot fall behind.

   Every transform asserts on its anchor. If the parent moves in a way
   that breaks one, this fails loudly rather than writing a page that
   is quietly missing a piece.
   ------------------------------------------------------------------ */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const PARENT = join(HERE, "..", "index.html");

/* Replace exactly once, or say which rule failed and on what. */
function sub(html, find, replace, label) {
  const hits = html.split(find).length - 1;
  if (hits !== 1) {
    throw new Error(
      `build.mjs: "${label}" matched ${hits} times, expected 1.\n` +
        `The parent page has moved. Anchor:\n  ${String(find).slice(0, 120)}`
    );
  }
  return html.replace(find, () => replace);
}

const FORK_HEADER = `<!-- Demo 3 — KYB workspace canvas.

     GENERATED. Do not edit this file — edit kyb-workspace/build.mjs and
     re-run it:  node portal-2.0/demo-3/kyb-workspace/build.mjs

     It is ../index.html plus the deltas named in that script: the base
     href, the fork's own stylesheets and scripts, the shell attributes
     that open the page straight into KYB, and the .kw-stage wrapper
     that puts .d1-main on a dot ground inside a white sheet.

     Everything else is the parent's, by construction — which is the
     point. Hand-merging this fork drifted badly enough that the
     sidebar and chat were a different build of the same product.

     Figma Portal-2.0-Design---2026 node 1274:15402
     https://www.figma.com/design/qtvqgc1fWEw0znhl4b8xPF/?node-id=1274-15402

     PATHS — this page lives one level below demo-3, and <base href="../">
     makes every relative URL (markup *and* the ones JS builds, e.g.
     d3-labs.js' iframe src) resolve against demo-3/ exactly as in the
     parent page. Nothing in css/ or js/ had to be duplicated. Files that
     belong to this fork are therefore addressed as kyb-workspace/… -->`;

/* auth-gate.js resolves sign-in/ against location.href rather than
   <base>, so from this folder it would 404. All the page needs from it
   is the ready class loader.css reveals .d1-shell with. */
const AUTH_SHIM = `<!-- auth-gate.js resolves sign-in/ against location.href (not <base>), so it
     would 404 from this folder. All it owes the page is the ready class
     that loader.css reveals .d1-shell with. -->
<script>
  document.body.classList.add("d1-app-ready");
  (function () {
    var loader = document.querySelector("[data-d1-loader]");
    if (!loader) return;
    loader.hidden = true;
    loader.style.display = "none";
  })();
</script>`;

